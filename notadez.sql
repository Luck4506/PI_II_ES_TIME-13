-- Tabela de instituição
CREATE TABLE INSTITUICAO (
  instituicao_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  nome VARCHAR2(150) NOT NULL,
  sigla VARCHAR2(20),
  CONSTRAINT PK_INSTITUICAO PRIMARY KEY (instituicao_id),
  CONSTRAINT UQ_INSTITUICAO_NOME UNIQUE (nome)
);

-- Tabela de docente
CREATE TABLE DOCENTE (
  docente_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  nome VARCHAR2(150) NOT NULL,
  email VARCHAR2(180) NOT NULL,
  telefone_celular  VARCHAR2(25),
  senha VARCHAR2(255) NOT NULL,
  CONSTRAINT PK_DOCENTE PRIMARY KEY (docente_id),
  CONSTRAINT UQ_DOCENTE_EMAIL UNIQUE (email)
);

-- Tabela de curso
CREATE TABLE CURSO (
  curso_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  instituicao_id NUMBER(10) NOT NULL,
  nome VARCHAR2(150) NOT NULL,
  CONSTRAINT PK_CURSO PRIMARY KEY (curso_id),
  CONSTRAINT UQ_CURSO_NOME_INST UNIQUE (instituicao_id, nome),
  CONSTRAINT FK_CURSO_INSTITUICAO FOREIGN KEY (instituicao_id)
    REFERENCES INSTITUICAO(instituicao_id)
);

-- Tabela associativa docente e instituição
CREATE TABLE DOCENTE_INSTITUICAO (
  docente_id NUMBER NOT NULL,
  instituicao_id NUMBER NOT NULL,
  CONSTRAINT PK_DOCENTE_INSTITUICAO PRIMARY KEY (docente_id, instituicao_id),
  CONSTRAINT FK_DI_DOCENTE FOREIGN KEY (docente_id)
    REFERENCES DOCENTE(docente_id),
  CONSTRAINT FK_DI_INSTITUICAO FOREIGN KEY (instituicao_id)
    REFERENCES INSTITUICAO(instituicao_id)
);

-- Tabela associativa docente e curso
CREATE TABLE DOCENTE_CURSO (
  docente_id NUMBER(10) NOT NULL,
  curso_id   NUMBER(10) NOT NULL,
  CONSTRAINT PK_DOCENTE_CURSO PRIMARY KEY (docente_id, curso_id),
  CONSTRAINT FK_DC_DOCENTE FOREIGN KEY (docente_id)
    REFERENCES DOCENTE(docente_id),
  CONSTRAINT FK_DC_CURSO FOREIGN KEY (curso_id)
    REFERENCES CURSO(curso_id)
);

-- Tabela de aluno
CREATE TABLE ALUNO (
  RA_aluno NUMBER(12),
  nome VARCHAR2(150) NOT NULL,
  data_nascimento DATE,
  criado_em DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_ALUNO PRIMARY KEY (RA_aluno)
);

-- Tornando RA_aluno auto-incremento
ALTER TABLE ALUNO MODIFY (
  RA_aluno NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1)
);

-- Tabela de disciplina
CREATE TABLE DISCIPLINA (
  codigo_disciplina NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  curso_id NUMBER(10) NOT NULL,
  nome VARCHAR2(150) NOT NULL,
  sigla VARCHAR2(20),
  codigo VARCHAR2(50),
  periodo_curso NUMBER(3),
  CONSTRAINT PK_DISCIPLINA PRIMARY KEY (codigo_disciplina),
  CONSTRAINT UQ_DISCIPLINA_CURSO_NOME UNIQUE (curso_id, nome),
  CONSTRAINT FK_DISCIPLINA_CURSO FOREIGN KEY (curso_id)
    REFERENCES CURSO(curso_id)
);


-- Tabela de componentes de nota
CREATE TABLE COMPONENTE_NOTA (
  componente_nota_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  codigo_disciplina NUMBER(10) NOT NULL,
  nome VARCHAR2(100) NOT NULL,
  sigla VARCHAR2(20),
  descricao VARCHAR2(4000),
  CONSTRAINT PK_COMPONENTE_NOTA PRIMARY KEY (componente_nota_id),
  CONSTRAINT UQ_COMPONENTE_DISCIPLINA_NOME UNIQUE (codigo_disciplina, nome),
  CONSTRAINT FK_COMPONENTE_DISCIPLINA FOREIGN KEY (codigo_disciplina)
    REFERENCES DISCIPLINA(codigo_disciplina)
);


-- Tabela de fórmula de nota final
CREATE TABLE FORMULA_NOTA_FINAL (
  formula_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  codigo_disciplina NUMBER(10) NOT NULL,
  expressao VARCHAR2(4000) NOT NULL,
  validada CHAR(1) DEFAULT 'N' NOT NULL,         -- 'S'/'N'
  usa_coluna_ajustada CHAR(1) DEFAULT 'N' NOT NULL,         -- 'S'/'N'
  validada_em DATE,
  criado_em DATE DEFAULT SYSDATE NOT NULL,
  atualizado_em DATE,
  CONSTRAINT PK_FORMULA PRIMARY KEY (formula_id),
  CONSTRAINT UQ_FORMULA_DISCIPLINA UNIQUE (codigo_disciplina),
  CONSTRAINT CK_FORMULA_VALIDADA CHECK (validada IN ('S','N')),
  CONSTRAINT CK_FORMULA_USA_AJUSTADA CHECK (usa_coluna_ajustada IN ('S','N')),
  CONSTRAINT FK_FORMULA_DISCIPLINA FOREIGN KEY (codigo_disciplina)
    REFERENCES DISCIPLINA(codigo_disciplina)
);

