-- NOTAS: LANÇAMENTOS E NOTA FINAL AJUSTADA
-- Lançamento de nota pertence a 1 TURMA, 1 ALUNO e 1 COMPONENTE_NOTA; 

CREATE TABLE LANCAMENTO_NOTA (
  codigo_turma NUMBER(10) NOT NULL,
  RA_aluno NUMBER(12) NOT NULL,
  componente_nota_id  NUMBER(10) NOT NULL,
  docente_id NUMBER(10) NOT NULL,
  valor NUMBER(7,3) NOT NULL,
  CONSTRAINT PK_LANCAMENTO_NOTA PRIMARY KEY (codigo_turma, RA_aluno, componente_nota_id),
  CONSTRAINT FK_LANCAMENTO_TURMA FOREIGN KEY (codigo_turma)
    REFERENCES TURMA(codigo_turma),
  CONSTRAINT FK_LANCAMENTO_ALUNO FOREIGN KEY (RA_aluno)
    REFERENCES ALUNO(RA_aluno),
  CONSTRAINT FK_LANCAMENTO_COMP FOREIGN KEY (componente_nota_id)
    REFERENCES COMPONENTE_NOTA(componente_nota_id),
  CONSTRAINT FK_LANCAMENTO_DOCENTE FOREIGN KEY (docente_id)
    REFERENCES DOCENTE(docente_id),
  CONSTRAINT CK_LANCAMENTO_VALOR CHECK (valor >= 0)
);


-- Nota Final Ajustada 
CREATE TABLE NOTA_FINAL_AJUSTADA (
  codigo_turma NUMBER(10) NOT NULL,
  RA_aluno NUMBER(12) NOT NULL,
  valor_nota_final NUMBER(7,3) NOT NULL,
  valor_nota_final_ajustada  NUMBER(7,3),
  CONSTRAINT PK_NOTA_FINAL_AJ PRIMARY KEY (codigo_turma, RA_aluno),
  CONSTRAINT FK_NFA_TURMA FOREIGN KEY (codigo_turma)
    REFERENCES TURMA(codigo_turma),
  CONSTRAINT FK_NFA_ALUNO FOREIGN KEY (RA_aluno)
    REFERENCES ALUNO(RA_aluno),
  CONSTRAINT CK_NFA_VALOR CHECK (valor_nota_final >= 0),
  CONSTRAINT CK_NFA_VALOR_AJ CHECK (valor_nota_final_ajustada IS NULL OR valor_nota_final_ajustada >= 0)
);

